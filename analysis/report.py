def _pct(x, nd=0):
    return f"{100 * x:.{nd}f}%"


def _money(x):
    s = "+" if x >= 0 else "-"
    return f"{s}${abs(x) / 1e6:.2f}M"


def _ci(lo, hi, nd=1):
    return f"{lo:.{nd}f} to {hi:.{nd}f}"


