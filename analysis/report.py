"""Render results/RESULTS.md: every number the README quotes, regenerated from the data."""
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
from panel import ROOT  # noqa: E402

RES = os.path.join(ROOT, "results")
UNITS = ("V", "A", "B")


def f(x, nd=2):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    if isinstance(x, (int, np.integer)):
        return f"{x:,}"
    ax = abs(x)
    if ax != 0 and (ax < 1e-3 or ax >= 1e5):
        return f"{x:.{nd}e}"
    return f"{x:,.{nd}f}"


def table(df, cols, fmt=None):
    fmt = fmt or {}
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmt.get(c, lambda v: f(v) if isinstance(v, (float, int, np.number)) else str(v))(r[c])
                                     for c in cols) + " |")
    return "\n".join(out)


def main():
    S = json.load(open(os.path.join(RES, "summary.json")))
    L = []
    w = L.append
    w("# Results\n")
    w("Generated by `analysis/report.py` from the collected data. Every figure in the README is regenerated by the `analyze` workflow.\n")
    w("## Sample\n")
    rows = []
    for l in UNITS:
        s = S[l]
        rows.append({"strategy": l, "start (UTC)": s["start"][:19], "end (UTC)": s["end"][:19], "minutes": s["minutes"],
                     "quote snapshots": s["n_quotes"], "coins quoted": s["n_coins_quoted"],
                     "coins estimated": s["n_coins_estimated"], "account value ($)": s["account_value"]})
    w(table(pd.DataFrame(rows), list(rows[0].keys())) + "\n")

    w("## Risk aversion\n")
    rows = []
    names = {"within": "within-coin levels (inverse-variance pooled)", "event": "fill-event study, 5 s (pooled)",
             "between": "between-coin cross-section (median of 10-min windows)"}
    for l in UNITS:
        s = S[l]
        for k, name in names.items():
            p = s["pooled"].get(k)
            if not p:
                continue
            ci = f"[{f(p['gamma_lo'])}, {f(p['gamma_hi'])}]" if "gamma_lo" in p else f"{f(p.get('share_windows_positive'))} of windows > 0"
            rows.append({"unit": l, "estimator": name, "gamma (1/$)": p["gamma"], "95% CI": ci,
                         "RRA on trading capital": p["rra_trading_capital"], "coins": p.get("coins", p.get("median_coins"))})
    w(table(pd.DataFrame(rows), list(rows[0].keys())) + "\n")
    w("Implied relative risk aversion = gamma x strategy account value.\n")
    rows = []
    for l in UNITS:
        c = S[l]["coin_gamma"]
        rows.append({"strategy": l, "skew sign correct (no controls)": c["share_skew_correct_sign_tb"],
                     "skew sign correct (controls)": c["share_skew_correct_sign_aug"],
                     "skew significant (controls)": c["share_skew_signif_aug"],
                     "fill-event skew sign correct": c["share_event_correct_sign"],
                     "median skew (bps per $10k)": c["median_skew_bps_per_10k_aug"]})
    w(table(pd.DataFrame(rows), list(rows[0].keys())) + "\n")

    w("## The levers HLP actually uses\n")
    rows = []
    for l in UNITS:
        t, z = S[l]["taker_threshold"], S[l]["size_skew"]
        rows.append({"inventory": {"V": "vault (A+B)", "A": "A own", "B": "B own"}[l],
                     "taker fills": t.get("n_taker"), "P(reduce) below": t.get("p_below"), "P(reduce) above": t.get("p_above"),
                     "z_bar": t.get("z_bar"), "z_bar 95% CI": f"[{f(t.get('z_bar_lo'))}, {f(t.get('z_bar_hi'))}]",
                     "LR vs no threshold": t.get("lr_stat_vs_flat"), "threshold ($/coin)": t.get("median_threshold_usd"),
                     "gamma_T (1/$)": t.get("gamma_T"), "reservation skew (bps/$10k)": t.get("reservation_skew_bps_per_10k"),
                     "size lean within (per $1k)": f"{f(z['within'], 4)} (t {f(z['within_t'], 1)})",
                     "size lean between (per $1k)": f"{f(z['between'], 4)} (t {f(z['between_t'], 1)})"})
    df = pd.DataFrame(rows)
    w(table(df, list(df.columns), fmt={"z_bar 95% CI": str, "size lean within (per $1k)": str, "size lean between (per $1k)": str, "inventory": str}) + "\n")
    w("Taker-implied gamma_T = 1 / z_bar^2 (GLFT with market orders: cross when omega*q exceeds the crossing cost). A lower bound, since waiting for a passive fill has option value. Median crossing cost (spread paid + fee): "
      + ", ".join(f"{l} {f(S[l]['taker_threshold'].get('median_cost_bps'))} bps" for l in UNITS) + ".\n")
    a = S["attribution"]
    w("**Whose inventory?** A's quotes regressed jointly on A's own inventory and the vault's net inventory "
      f"(corr {f(a['corr_x_own_x_vault'], 3)}). Size lean: own {f(a['size_lean']['Q_own_1k']['coef'], 4)} (t {f(a['size_lean']['Q_own_1k']['t'], 1)}), "
      f"vault {f(a['size_lean']['Q_vault_1k']['coef'], 4)} (t {f(a['size_lean']['Q_vault_1k']['t'], 1)}). "
      f"Price skew (within coin): own {f(a['within']['x_own']['coef'], 4)} (t {f(a['within']['x_own']['t'], 1)}), "
      f"vault {f(a['within']['x_vault']['coef'], 4)} (t {f(a['within']['x_vault']['t'], 1)}).\n")
    for l in ("A", "B"):
        c = S[l].get("cross_account", {})
        if c:
            w(f"**Cross-account repricing, Strategy {l}** (bps of quote-centre move per $10k filled, 5 s, textbook sign positive): "
              + ", ".join(f"{k.replace('_', ' ')} {f(v['bps_per_10k_fill'], 1)} (t {f(v['t'], 1)}, n {v['n']})" for k, v in c.items()) + ".\n")

    w("## Over-identification and the fill curve\n")
    rows = []
    for l in UNITS:
        o, i = S[l]["overid"], S[l]["intensity"]
        rows.append({"strategy": l, "median psi / (1/k + D b/2)": o["median_psi_ratio"], "share > 1": o["share_psi_ratio_gt1"],
                     "spread not rationalisable by any gamma": o["share_spread_unrationalisable"],
                     "median half spread (bps)": o["median_psi_bps"], "median 1/k (bps)": o["median_markup_bps"],
                     "median flow share": i.get("median_flow_share"), "exp beats power law (AIC)": i["share_exp_beats_pow_aic"]})
    w(table(pd.DataFrame(rows), list(rows[0].keys())) + "\n")

    w("## What moves the quote centre\n")
    for l in UNITS:
        rp = S[l]["reference_price"]
        w(f"**Strategy {l}** (pooled, coin fixed effects, coin-clustered t-stats; c in bps, inventory in $10k x sigma^2)\n")
        rows = []
        for spec in ("textbook", "plus_basis", "full"):
            r = rp[spec]
            row = {"spec": spec, "R^2": r["r2"], "n": r["n"]}
            for k, v in r["params"].items():
                row[k] = f"{f(v, 3)} ({f(r['t'][k], 1)})"
            rows.append(row)
        df = pd.DataFrame(rows).fillna("")
        w(table(df, list(df.columns), fmt={c: str for c in df.columns if c not in ("R^2", "n")}) + "\n")
        wr = rp["within_r2"]
        w(f"Within-coin R^2: inventory only {f(wr['inventory_only'], 3)}, everything but inventory {f(wr['all_but_inventory'], 3)}, "
          f"all {f(wr['all'], 3)}, partial R^2 of inventory {f(wr['partial_inventory'], 4)}.\n")

    w("## Shape of the inventory response\n")
    rows = []
    for l in UNITS:
        s = S[l]["inventory_shape"]
        rows.append({"strategy": l, "linear slope (bps per unit z)": s["lin_slope"], "t": s["lin_t"], "slope when long": s["slope_long"],
                     "slope when short": s["slope_short"], "t(long = short)": s["asym_t"], "t(z^2)": s["cub_t2"], "t(z^3)": s["cub_t3"],
                     "R^2 linear": s["lin_r2"], "R^2 cubic": s["cub_r2"]})
    w(table(pd.DataFrame(rows), list(rows[0].keys())) + "\n")

    w("## Markouts (bps from HLP's side, $-weighted)\n")
    for l in UNITS:
        p = os.path.join(RES, f"markouts_{l}.csv")
        if os.path.exists(p):
            m = pd.read_csv(p)
            w(f"**Strategy {l}**\n")
            w(table(m, ["type", "n", "usd", "edge_bps", "mo1", "mo5", "mo10", "mo30", "mo60", "mo300"]) + "\n")

    w("## Taking liquidity\n")
    for l in UNITS:
        t = S[l]["taker"]
        df = pd.DataFrame(t["summary"])
        df["type"] = np.where(df.crossed == 1, "taker", "maker")
        w(f"**Strategy {l}**\n")
        w(table(df, ["type", "n", "usd", "share_reducing", "share_with_basis", "mean_signed_basis_bps"]) + "\n")
        lg = t["logit"]
        w("Logit P(taker): " + ", ".join(f"{k} {f(v, 3)} (t {f(lg['t'][k], 1)})" for k, v in lg["params"].items()) + f", n={lg['n']}.\n")

    w("## Other tests\n")
    rows = []
    for l in UNITS:
        s = S[l]
        rows.append({"strategy": l, "spread elasticity to vol": f"{f(s['vol_scaling']['elasticity_psi_sigma'])} ({f(s['vol_scaling']['se'])})",
                     "own inventory (bps/$10k)": f"{f(s['portfolio']['params']['Q10k'], 3)} (t {f(s['portfolio']['t']['Q10k'], 1)})",
                     "rest of book net (bps/$100k)": f"{f(s['portfolio']['params']['other_net_100k'], 3)} (t {f(s['portfolio']['t']['other_net_100k'], 1)})",
                     "gross book (bps/$1M)": f"{f(s['portfolio']['params']['gross_1m'], 3)} (t {f(s['portfolio']['t']['gross_1m'], 1)})",
                     "coins ever one-sided": f(s["quote_pulling"]["share_coins_ever_one_sided"])})
    df = pd.DataFrame(rows)
    w(table(df, list(df.columns), fmt={c: str for c in df.columns}) + "\n")
    if "fear_corr" in S["A"]:
        rows = [{"strategy": l, **S[l].get("fear_corr", {})} for l in "AB"]
        df = pd.DataFrame(rows)
        df["gamma_p10_p90"] = df.gamma_p10_p90.apply(lambda v: f"[{f(v[0])}, {f(v[1])}]" if isinstance(v, list) else "")
        w("**Fear gauge correlations (10-minute windows)**\n")
        w(table(df, list(df.columns)) + "\n")
    t = S["twin"]
    w("**Twin strategies.** " + ", ".join(f"{k} {f(v) if isinstance(v, (int, float)) else v}" for k, v in t.items()) + ".\n")

    w("## Per-coin estimates (Strategy A, 25 most active coins)\n")
    p = pd.read_csv(os.path.join(RES, "params_A.csv")).sort_values("n_aggr", ascending=False).head(25)
    cols = ["coin", "sigma_bps_s", "psi_bps", "markup_bps", "flow_share", "D_usd", "skew_bps_10k_aug", "t_aug", "gamma_aug",
            "skew_bps_10k_ev", "t_ev", "phi_basis", "psi_ratio"]
    cols = [c for c in cols if c in p.columns]
    w(table(p, cols) + "\n")
    open(os.path.join(RES, "RESULTS.md"), "w").write("\n".join(L))
    print("wrote results/RESULTS.md")


if __name__ == "__main__":
    main()
